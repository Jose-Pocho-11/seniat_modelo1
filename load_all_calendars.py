def load_data():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    years = [2023, 2024, 2025, 2026]
    
    # 1. CALENDARIO SENIAT
    for anio in years:
        for quincena, meses in CALENDARIO_SENIAT.items():
            for mes, dias in meses.items():
                for terminal, dia_vencimiento in dias.items():
                    cursor.execute('''
                        INSERT OR REPLACE INTO calendarios 
                        (anio, mes, quincena, terminal_rif, dia_vencimiento) 
                        VALUES (?, ?, ?, ?, ?)
                    ''', (anio, mes, quincena, terminal, dia_vencimiento))
                    
    # 2. NUEVA TABLA (DPP)
    for anio in years:
        for mes, dias in NUEVA_TABLA.items():
            for terminal, dia_vencimiento in dias.items():
                cursor.execute('''
                    INSERT OR REPLACE INTO calendarios_dpp 
                    (anio, mes, terminal_rif, dia_vencimiento) 
                    VALUES (?, ?, ?, ?)
                ''', (anio, mes, terminal, dia_vencimiento))
                
    conn.commit()
    conn.close()
    print("Datos insertados con exito!")

